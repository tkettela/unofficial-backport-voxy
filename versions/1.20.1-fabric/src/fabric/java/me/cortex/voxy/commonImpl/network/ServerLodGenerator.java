package me.cortex.voxy.commonImpl.network;

import it.unimi.dsi.fastutil.longs.LongOpenHashSet;
import me.cortex.voxy.common.Logger;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.MinecraftServer;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.TicketType;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.chunk.ChunkStatus;
import net.minecraft.world.level.chunk.LevelChunk;

import java.util.ArrayDeque;
import java.util.Comparator;
import java.util.HashMap;
import java.util.Map;
import java.util.Optional;
import java.util.UUID;
import java.util.concurrent.ConcurrentLinkedQueue;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.atomic.AtomicInteger;

//Generates the terrain around players that receive LoDs, in the background, so the LoD view fills up without
// having to pregenerate the world. Never-generated chunks are found with cheap disk lookups, then generated by
// minecraft with a temporary ticket, a few at a time, slowing down when the server tick time gets too high.
// Freshly generated chunks are pushed to the players right away.
public final class ServerLodGenerator {
    private ServerLodGenerator() {}

    private static final TicketType<ChunkPos> TICKET = TicketType.create("voxy_lod_generation", Comparator.comparingLong(ChunkPos::toLong));
    private static final int MAX_PROBES_IN_FLIGHT = 64;
    private static final int MAX_SCAN_PER_TICK = 4096;
    private static final int MAX_CHECKED_POSITIONS = 4_000_000;
    //Once a player's area is fully generated, look again after this long (new areas can appear when the radius changes)
    private static final long RESCAN_INTERVAL_MS = 120_000;

    private record Probe(ServerLevel level, long pos, boolean needsGeneration) {}
    private record GenTask(ServerLevel level, long pos) {}

    private static final class Spiral {
        private ResourceKey<Level> dimension;
        private int centerX, centerZ;
        private int ring, index;
        private boolean done;
        private long doneAt;
        //Direction the player was looking when the spiral started, the first pass only covers that half
        private double dirX, dirZ;
        private int pass;

        private void reset(ResourceKey<Level> dimension, int x, int z, double dirX, double dirZ) {
            this.dimension = dimension;
            this.centerX = x;
            this.centerZ = z;
            this.ring = 0;
            this.index = 0;
            this.done = false;
            this.dirX = dirX;
            this.dirZ = dirZ;
            this.pass = 0;
        }

        //Generate what the player is heading towards first, the rest on the second pass
        private boolean skipThisPass(int dx, int dz) {
            return this.pass == 0 && (dx * this.dirX + dz * this.dirZ) < 0;
        }

        //Next offset of a square spiral, Long.MAX_VALUE once past the radius on the last pass
        private long next(int radius) {
            if (this.ring > radius) {
                if (this.pass != 0) return Long.MAX_VALUE;
                this.pass = 1;
                this.ring = 0;
                this.index = 0;
            }
            int r = this.ring;
            int dx, dz;
            if (r == 0) {
                dx = 0; dz = 0;
                this.ring++;
                this.index = 0;
            } else {
                int side = this.index / (2 * r);
                int off = this.index % (2 * r);
                switch (side) {
                    case 0 -> {dx = -r + off; dz = -r;}
                    case 1 -> {dx = r; dz = -r + off;}
                    case 2 -> {dx = r - off; dz = r;}
                    default -> {dx = -r; dz = r - off;}
                }
                if (++this.index >= 8 * r) {
                    this.ring++;
                    this.index = 0;
                }
            }
            return ChunkPos.asLong(dx, dz);
        }
    }

    //All only touched from the server thread, except the probe results queue and counter
    private static final Map<UUID, Spiral> SPIRALS = new HashMap<>();
    private static final Map<ResourceKey<Level>, LongOpenHashSet> CHECKED = new HashMap<>();
    private static final ArrayDeque<GenTask> GEN_QUEUE = new ArrayDeque<>();
    private static final ConcurrentLinkedQueue<Probe> PROBE_RESULTS = new ConcurrentLinkedQueue<>();
    private static final AtomicInteger PROBES_IN_FLIGHT = new AtomicInteger();
    private static int generating;
    private static int generationLimit = 2;
    private static long generatedTotal;
    private static long lastLog;
    private static long lastLoggedTotal;

    static void reset() {
        SPIRALS.clear();
        CHECKED.clear();
        GEN_QUEUE.clear();
        PROBE_RESULTS.clear();
        //generating is not reset: chunks already generating still finish and decrement it
        generationLimit = 2;
    }

    static java.util.List<String> statusLines(MinecraftServer server) {
        var config = ServerLodConfig.CONFIG;
        String state = !isActive(server) ? "off" : "on";
        return java.util.List.of("Generation: " + state + ", radius " + Math.min(config.autoGenerateRadius, config.maxRadiusChunks)
                + " chunks, " + generating + " generating (limit " + generationLimit + "/" + config.getAutoGenerateMaxConcurrent() + "), "
                + GEN_QUEUE.size() + " queued, " + generatedTotal + " generated since start");
    }

    static boolean isActive(MinecraftServer server) {
        var config = ServerLodConfig.CONFIG;
        if (!config.autoGenerate || config.autoGenerateRadius <= 0) return false;
        //Off by default in singleplayer/LAN so saves dont grow without the player knowing
        return server.isDedicatedServer() || config.autoGenerateOnIntegratedServer;
    }

    static void tick(MinecraftServer server, ExecutorService workers, int tickCounter) {
        var config = ServerLodConfig.CONFIG;
        if (!isActive(server)) {
            if (!GEN_QUEUE.isEmpty() || !SPIRALS.isEmpty()) {
                //Turned off in game: drop the plan, chunks already generating finish on their own
                GEN_QUEUE.clear();
                SPIRALS.clear();
                CHECKED.clear();
            }
            return;
        }

        //Keep the server smooth: adapt how many chunks generate at once to the tick time
        if (tickCounter % 20 == 0) {
            float mspt = server.getAverageTickTime();
            int max = config.getAutoGenerateMaxConcurrent();
            if (mspt > config.targetTickTimeMs) {
                generationLimit = Math.max(1, generationLimit * 2 / 3);
            } else if (mspt < config.targetTickTimeMs * 0.75f) {
                generationLimit = Math.min(max, generationLimit + 1);
            }
            generationLimit = Math.min(generationLimit, max);
        }

        Probe probe;
        while ((probe = PROBE_RESULTS.poll()) != null) {
            if (probe.needsGeneration) {
                GEN_QUEUE.add(new GenTask(probe.level, probe.pos));
            }
        }

        while (generating < generationLimit && !GEN_QUEUE.isEmpty()) {
            startGeneration(server, GEN_QUEUE.poll(), workers);
        }

        if (GEN_QUEUE.size() < generationLimit * 4) {
            scan(server, workers);
        }

        long now = System.currentTimeMillis();
        if (now - lastLog > 60_000 && generatedTotal != lastLoggedTotal) {
            lastLog = now;
            Logger.info("Voxy LoD generation: " + (generatedTotal - lastLoggedTotal) + " chunks generated in the last minute (" + generating + " in progress, limit " + generationLimit + ")");
            lastLoggedTotal = generatedTotal;
        }
    }

    private static void scan(MinecraftServer server, ExecutorService workers) {
        var config = ServerLodConfig.CONFIG;
        int radius = Math.min(config.autoGenerateRadius, config.maxRadiusChunks);
        int viewDistance = server.getPlayerList().getViewDistance();
        long radiusSq = (long) radius * radius;
        long now = System.currentTimeMillis();

        var players = ServerLodStreamer.streamingPlayers(server);
        SPIRALS.keySet().removeIf(uuid -> players.stream().noneMatch(p -> p.getUUID().equals(uuid)));
        if (players.isEmpty()) return;

        int scanBudget = MAX_SCAN_PER_TICK;
        for (var player : players) {
            var level = player.serverLevel();
            var dimension = level.dimension();
            int px = player.chunkPosition().x;
            int pz = player.chunkPosition().z;
            var spiral = SPIRALS.computeIfAbsent(player.getUUID(), k -> new Spiral());
            if (spiral.dimension != dimension || Math.abs(px - spiral.centerX) > 8 || Math.abs(pz - spiral.centerZ) > 8
                    || (spiral.done && now - spiral.doneAt > RESCAN_INTERVAL_MS)) {
                var look = player.getLookAngle();
                double length = Math.sqrt(look.x * look.x + look.z * look.z);
                spiral.reset(dimension, px, pz, length < 1.0E-3 ? 0 : look.x / length, length < 1.0E-3 ? 0 : look.z / length);
            }
            if (spiral.done) continue;

            var checked = CHECKED.computeIfAbsent(dimension, k -> new LongOpenHashSet());
            if (checked.size() > MAX_CHECKED_POSITIONS) {
                checked.clear();
            }

            while (scanBudget > 0 && PROBES_IN_FLIGHT.get() < MAX_PROBES_IN_FLIGHT) {
                long offset = spiral.next(radius);
                if (offset == Long.MAX_VALUE) {
                    spiral.done = true;
                    spiral.doneAt = now;
                    break;
                }
                scanBudget--;
                int dx = ChunkPos.getX(offset);
                int dz = ChunkPos.getZ(offset);
                if ((long) dx * dx + (long) dz * dz > radiusSq) continue;
                //The vanilla view distance is generated by minecraft itself
                if (Math.max(Math.abs(dx), Math.abs(dz)) <= viewDistance) continue;
                if (spiral.skipThisPass(dx, dz)) continue;

                int cx = spiral.centerX + dx;
                int cz = spiral.centerZ + dz;
                long pos = ChunkPos.asLong(cx, cz);
                //Never generate outside the world border
                if (!level.getWorldBorder().isWithinBounds(new ChunkPos(cx, cz))) continue;
                if (!checked.add(pos)) continue;
                if (level.getChunkSource().getChunkNow(cx, cz) != null) continue;//Loaded, so fully generated

                long cached = ServerLodStreamer.cachedState(dimension, pos);
                if (ServerLodStreamer.isCachedMissing(cached)) {
                    GEN_QUEUE.add(new GenTask(level, pos));
                    continue;
                }
                if (cached != VoxyNetworking.UNKNOWN_TIMESTAMP) continue;//Known to exist on disk

                //Unknown, look at the stored chunk off thread
                PROBES_IN_FLIGHT.incrementAndGet();
                level.getChunkSource().chunkMap.read(new ChunkPos(cx, cz)).handleAsync((tag, error) -> {
                    try {
                        PROBE_RESULTS.add(new Probe(level, pos, error == null && needsGeneration(tag)));
                    } finally {
                        PROBES_IN_FLIGHT.decrementAndGet();
                    }
                    return null;
                }, workers);
            }
            if (scanBudget <= 0) break;
        }
    }

    private static boolean needsGeneration(Optional<CompoundTag> optionalTag) {
        if (optionalTag.isEmpty()) return true;
        var tag = optionalTag.get();
        if (tag.contains("Level")) {
            tag = tag.getCompound("Level");//Pre 1.18 chunk format
        }
        return !ChunkStatus.byName(tag.getString("Status")).isOrAfter(ChunkStatus.FULL);
    }

    private static void startGeneration(MinecraftServer server, GenTask task, ExecutorService workers) {
        var level = task.level;
        if (server.getLevel(level.dimension()) != level) return;//Level went away
        var chunkPos = new ChunkPos(task.pos);
        var source = level.getChunkSource();
        if (source.getChunkNow(chunkPos.x, chunkPos.z) != null) return;
        if (!level.getWorldBorder().isWithinBounds(chunkPos)) return;//The border may have shrunk since it was queued

        generating++;
        //Keep the chunk alive until it is fully generated, then let minecraft save and unload it normally
        source.addRegionTicket(TICKET, chunkPos, 0, chunkPos);
        //getChunkFuture blocks until the chunk is done when called on the server thread, so call it from a worker:
        // from another thread it only schedules the work on the server thread and returns right away
        java.util.concurrent.CompletableFuture.supplyAsync(() -> source.getChunkFuture(chunkPos.x, chunkPos.z, ChunkStatus.FULL, true), workers)
                .thenCompose(future -> future)
                .whenCompleteAsync((result, error) -> {
            generating = Math.max(0, generating - 1);
            try {
                if (error == null && result != null) {
                    var chunk = result.left().orElse(null);
                    if (chunk instanceof LevelChunk levelChunk) {
                        generatedTotal++;
                        ServerLodStreamer.pushLoadedChunk(server, level, levelChunk);
                    }
                } else if (error != null) {
                    Logger.warn("Voxy LoD generation failed for chunk " + chunkPos + ": " + error);
                }
            } finally {
                source.removeRegionTicket(TICKET, chunkPos, 0, chunkPos);
            }
        }, server);
    }
}
